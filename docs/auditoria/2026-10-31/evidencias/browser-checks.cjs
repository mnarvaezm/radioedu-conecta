// Disposable localhost audit. No external requests or real messages.
const { chromium } = require('@playwright/test');
const fs = require('fs');
const base = 'http://localhost:8092';
const output = [];
const log = (name, data) => { output.push({ name, data }); console.log(name, JSON.stringify(data)); };
(async () => {
 const browser = await chromium.launch({ channel: 'msedge', headless: true });
 const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
 let tileRequests = 0;
 const badResponses = [];
 await context.route('**/*', route => {
  const url = new URL(route.request().url());
  if (url.hostname.endsWith('tile.openstreetmap.org')) tileRequests++;
  return url.origin === base ? route.continue() : route.abort();
 });
 const page = await context.newPage();
 page.on('response', r => { if (r.status() >= 400) badResponses.push({url:r.url(),status:r.status()}); });
 await page.goto(base + '/wp-login.php');
 await page.locator('#user_login').fill('audit_admin');
 await page.locator('#user_pass').fill('local-audit-only');
 await Promise.all([page.waitForURL('**/wp-admin/**'), page.locator('#wp-submit').click()]);
 await page.goto(base + '/?page_id=65');
 await page.locator('.radioedu-card').first().waitFor();
 log('directory', {cards:await page.locator('.radioedu-card').count(), heading:await page.locator('#radioedu-results-heading').innerText(), tilesBeforeConsent:tileRequests});
 await page.locator('#radioedu-btn-toggle-map').click();
 log('map_before_consent', {tiles:tileRequests});
 await page.locator('#radioedu-btn-accept-map').click();
 await page.locator('.leaflet-marker-icon').first().waitFor();
 log('map_loaded', {markers:await page.locator('.leaflet-marker-icon').count(), loadMoreVisible:await page.locator('#radioedu-btn-load-more').isVisible(),heading:await page.locator('#radioedu-results-heading').innerText(), tileAttempts:tileRequests});
 await page.locator('#radioedu-btn-toggle-map').click();
 const buttons = page.locator('.radioedu-card .radioedu-btn-match');
 await buttons.nth(0).click();
 const oldId = await page.locator('#radioedu-match-receptor').inputValue();
 const emisorOptions = await page.locator('#radioedu-match-emisor option').evaluateAll(els=>els.map(e=>e.value));
 await page.locator('#radioedu-match-emisor').selectOption(emisorOptions.find(id=>id!==oldId));
 await page.locator('#radioedu-match-idea').fill('Audit first request');
 let heldRoute;
 let capturedPayload;
 const held = new Promise(resolve => {
  context.route(/colaboraciones/, route => { heldRoute=route; capturedPayload=route.request().postDataJSON(); resolve(); });
 });
 await page.locator('#radioedu-btn-submit-match').click();
 await held;
 await page.locator('#radioedu-btn-close-drawer').click();
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('#radioedu-match-drawer')).display==='none');
 await buttons.nth(1).click();
 const newId = await page.locator('#radioedu-match-receptor').inputValue();
 const newLabel = await page.locator('#radioedu-match-receptor-txt').inputValue();
 await heldRoute.fulfill({ status:201, contentType:'application/json', body:JSON.stringify({success:true,message:'Audit delayed success'}) });
 await page.waitForFunction(()=>!document.querySelector('#radioedu-btn-submit-match').disabled);
 log('drawer_race', {oldId,newId,newLabel,idAfterDelayedSuccess:await page.locator('#radioedu-match-receptor').inputValue(),labelAfterDelayedSuccess:await page.locator('#radioedu-match-receptor-txt').inputValue(),originalRequest:capturedPayload.centro_receptor_id});
 await page.screenshot({path:'docs/auditoria/2026-10-31/evidencias/drawer-race.png',fullPage:false});
 await page.locator('#radioedu-btn-close-drawer').click();
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('#radioedu-match-drawer')).display==='none');
 await page.setViewportSize({width:320,height:800});
 log('mobile_320', await page.evaluate(()=>({viewport:innerWidth,documentWidth:document.documentElement.scrollWidth,gridWidth:document.querySelector('#radioedu-cards-container').getBoundingClientRect().width,cardWidth:document.querySelector('.radioedu-card').getBoundingClientRect().width})));
 await page.screenshot({path:'docs/auditoria/2026-10-31/evidencias/mobile-320.png',fullPage:false});
 // Exercise cookie authentication with missing and invalid nonce against the real HTTP server.
 const api = base + '/?rest_route=/radioedu-conecta/v1/colaboraciones';
 const without = await context.request.post(api,{data:capturedPayload});
 const invalid = await context.request.post(api,{headers:{'X-WP-Nonce':'invalid'},data:capturedPayload});
 log('http_nonces',{missing:{status:without.status(),body:await without.json()},invalid:{status:invalid.status(),body:await invalid.json()}});
 log('http_errors',badResponses);
 const noJs=await browser.newContext({javaScriptEnabled:false});
 const noJsPage=await noJs.newPage();
 await noJsPage.goto(base+'/?page_id=65');
 log('no_javascript',{cards:await noJsPage.locator('.radioedu-card').count(),text:await noJsPage.locator('#radioedu-results-heading').innerText()});
 await browser.close();
 fs.writeFileSync('docs/auditoria/2026-10-31/evidencias/browser-checks.json',JSON.stringify(output,null,2));
})().catch(error=>{fs.writeFileSync('docs/auditoria/2026-10-31/evidencias/browser-checks.json',JSON.stringify(output,null,2));console.error(error);process.exitCode=1;});
